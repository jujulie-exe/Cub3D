#include "../../include/cube3d.h"

void	free_double_array(char ***ar)
{
	size_t	i;

	i = 0;
	if (ar && *ar)
	{
		while ((*ar)[i])
		{
			free((*ar)[i]);
			(*ar)[i] = NULL;
			i++;
		}
		free(*ar);
		*ar = NULL;
	}
}
